#!/usr/bin/env node
// Copy example source from cosmonapse-examples into the site.
//
//   node scripts/sync-examples.mjs [path/to/cosmonapse-examples]
//
// For each example below, writes app/examples/<slug>/code.ts exporting
// CODE: { "<path inside the example>": "<file contents>" }. The example
// pages render from these strings, so what the site shows is exactly what
// the repo runs. Re-run after changing an example; never edit code.ts.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const site = path.resolve(here, "..");
const repo = path.resolve(process.argv[2] ?? path.join(site, "..", "cosmonapse-examples"));

// folder in cosmonapse-examples -> slug under app/examples/, or a site path
// (containing "/") relative to app/ for pages that live elsewhere.
export const EXAMPLES = {
  "01-quickstart": "core/quickstart",
  "02-building-a-neuron": "building-a-neuron",
  "03-round-robin": "round-robin",
  "04-pathway": "pathway",
  "05-orchestrator-api": "orchestrator-api",
  "06-engram-integration": "engram-integration",
  "07-no-orchestrator": "no-orchestrator",
  "08-real-world-neurons": "real-world-neurons",
  "09-capability-routing": "capability-routing",
  "10-bidding": "bidding",
  "11-rag": "rag",
  "12-rag-mcp": "rag-mcp",
  "13-retry": "retry",
  "14-agent": "agent",
  "15-claude-harness": "claude-harness",
  "16-rag-cli": "rag-cli",
  "17-receptors": "receptors",
  "18-simple-chat-hf": "simple-chat",
};

// Folders whose modules are components, plus root files worth showing.
const DIRS = ["neurons", "engram", "effector", "receptors"];
const ROOT_FILES = ["brain.py", "config.py", "helpers.py", "index.py", "embeddings.py",
  "demo.py", "cli.py", "flask_app.py", "wsgi_app.py", "handlers_reference.py"];
const SKIP = new Set(["__init__.py"]);
// Files never copied into the site, per example (e.g. a config that names a
// private endpoint).
const EXCLUDE = { "15-claude-harness": ["config.py"] };

function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    if (e.name === "__pycache__") return [];
    const p = path.join(dir, e.name);
    if (e.isDirectory()) return walk(p);
    return e.name.endsWith(".py") && !SKIP.has(e.name) ? [p] : [];
  });
}

let total = 0;
for (const [folder, slug] of Object.entries(EXAMPLES)) {
  const base = path.join(repo, folder);
  if (!fs.existsSync(base)) {
    console.error(`missing ${base}`);
    process.exitCode = 1;
    continue;
  }
  const files = [
    ...ROOT_FILES.map((f) => path.join(base, f)).filter((f) => fs.existsSync(f)),
    ...DIRS.flatMap((d) => walk(path.join(base, d))),
  ];
  const code = {};
  for (const f of files.sort()) {
    const rel = path.relative(base, f).split(path.sep).join("/");
    if ((EXCLUDE[folder] ?? []).includes(rel)) continue;
    code[rel] = fs.readFileSync(f, "utf8").replace(/\r\n/g, "\n");
  }
  const out = slug.includes("/")
    ? path.join(site, "app", slug, "code.ts")
    : path.join(site, "app", "examples", slug, "code.ts");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  const body =
    `// GENERATED by scripts/sync-examples.mjs from cosmonapse-examples/${folder}.\n` +
    `// Do not edit - change the example and re-run the script.\n\n` +
    `export const CODE: Record<string, string> = ${JSON.stringify(code, null, 2)};\n`;
  fs.writeFileSync(out, body);
  total += Object.keys(code).length;
  console.log(`${slug.padEnd(20)} ${Object.keys(code).length} files`);
}
console.log(`${total} files synced from ${repo}`);
